import { PrismaClient } from '@prisma/client'
const db = new PrismaClient()
const now = new Date()
const t30 = new Date(now.getTime() - 30*864e5)
const total = await db.appointment.count()
const last30 = await db.appointment.count({ where: { date: { gte: t30 } } })
const upcoming = await db.appointment.count({ where: { date: { gte: now }, status: 'onaylandi' } })
const upcomingAll = await db.appointment.count({ where: { date: { gte: now } } })
console.log('appointments total:', total, '| last30d:', last30, '| upcoming(all):', upcomingAll, '| upcoming(onaylandi):', upcoming)
const byStatus = await db.appointment.groupBy({ by: ['status'], _count: true })
console.log('byStatus:', JSON.stringify(byStatus))
const members = await db.member.count()
console.log('members:', members)
await db.$disconnect()
